create table if not exists public.status_events (
  event_id bigint generated by default as identity primary key,
  entity_type text not null,
  entity_id text not null,
  from_status text,
  to_status text not null,
  note text,
  actor_email text,
  created_at timestamptz not null default now()
);
create index if not exists status_events_entity_idx on public.status_events(entity_type, entity_id, created_at desc);
alter table public.status_events enable row level security;
drop policy if exists auth_all_status_events on public.status_events;
create policy auth_all_status_events on public.status_events for all to authenticated using (true) with check (true);

create or replace function public.log_batch_status_event()
returns trigger language plpgsql security invoker set search_path=public as $$
begin
  if old.status is distinct from new.status then
    insert into public.status_events(entity_type,entity_id,from_status,to_status,actor_email)
    values('batch',new.batch_id,old.status,new.status,auth.jwt()->>'email');
  end if;
  return new;
end; $$;

create or replace function public.log_product_status_event()
returns trigger language plpgsql security invoker set search_path=public as $$
begin
  if old.inventory_status is distinct from new.inventory_status then
    insert into public.status_events(entity_type,entity_id,from_status,to_status,actor_email)
    values('product',new.product_id,old.inventory_status,new.inventory_status,auth.jwt()->>'email');
  end if;
  return new;
end; $$;

drop trigger if exists trg_batches_log_status on public.batches;
create trigger trg_batches_log_status after update of status on public.batches for each row execute function public.log_batch_status_event();
drop trigger if exists trg_products_log_status on public.products;
